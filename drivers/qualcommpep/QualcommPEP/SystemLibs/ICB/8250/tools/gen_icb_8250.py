#!/usr/bin/env python3
"""Generate SM8250 ICB topology for QualcommPEP from Linux drivers/interconnect/qcom/sm8250.c
and the BUSARB routes used by the Kona DSDT.
usage: gen_icb_8250.py <linux sm8250.c> <kona dsdt.dsl> <out bcm_nodes_gen.c> <out icb_catalog_8250.inc> <out routes.inc>"""
import re, sys, collections
lx, dsl, out_bcm, out_cat, out_routes = sys.argv[1:6]
L = open(lx).read()
nodes = {}
for m in re.finditer(r'static struct qcom_icc_node (\w+) = \{(.*?)\n\};', L, re.S):
    n, b = m.groups()
    ch = int((re.search(r'\.channels = (\d+)', b) or [0, 1])[1])
    bw = int(re.search(r'\.buswidth = (\d+)', b).group(1))
    lk = re.findall(r'&(\w+)', (re.search(r'\.link_nodes = \{(.*?)\}', b, re.S) or [0, ''])[1]) if '.link_nodes' in b else []
    nodes[n] = dict(ch=ch, bw=bw, links=lk)
bcms = []
for m in re.finditer(r'static struct qcom_icc_bcm bcm_(\w+) = \{(.*?)\n\};', L, re.S):
    b = m.group(2)
    name = re.search(r'\.name = "(\w+)"', b).group(1)
    ka = 'keepalive = true' in b
    em = re.search(r'\.enable_mask = (BIT\((\d+)\)|0x[0-9a-fA-F]+)', b)
    mask = (1 << int(em.group(2))) if em and em.group(2) else (int(em.group(1), 16) if em else 0)
    ns = re.findall(r'&(\w+)', re.search(r'\.nodes = \{(.*?)\}', b, re.S).group(1))
    if name not in [x[0] for x in bcms]:
        bcms.append((name, ka, mask, ns))
node_bcms = collections.defaultdict(list)
for i, (name, ka, mask, ns) in enumerate(bcms):
    for n in ns:
        node_bcms[n].append(i)

KONA = {  # Kona DSDT ICBID symbol -> Linux node
 'ICBID_MASTER_APPSS_PROC': 'chm_apps', 'ICBID_SLAVE_DISPLAY_CFG': 'qhs_display_cfg',
 'ICBID_SLAVE_PCIE_0_CFG': 'qhs_pcie0_cfg', 'ICBID_SLAVE_PCIE_1_CFG': 'qhs_pcie1_cfg',
 'ICBID_SLAVE_QUP_0': 'qhs_qup0', 'ICBID_SLAVE_QUP_1': 'qhs_qup1', 'ICBID_SLAVE_QUP_2': 'qhs_qup2',
 'ICBID_SLAVE_UFS_MEM_CFG': 'qhs_ufs_mem_cfg', 'ICBID_SLAVE_USB3_0': 'qhs_usb3_0',
 'ICBID_SLAVE_USB3_1': 'qhs_usb3_1', 'ICBID_SLAVE_VENUS_CFG': 'qhs_venus_cfg',
 'ICBID_MASTER_CAMNOC_HF0': 'qnm_camnoc_hf', 'ICBID_MASTER_CAMNOC_HF1': 'qnm_camnoc_hf',
 'ICBID_MASTER_CAMNOC_SF': 'qnm_camnoc_sf', 'ICBID_MASTER_GFX3D': 'qnm_gpu',
 'ICBID_MASTER_LLCC': 'llcc_mc', 'ICBID_SLAVE_EBI1': 'ebi', 'ICBID_MASTER_MDP0': 'qxm_mdp0',
 'ICBID_MASTER_MNOC_HF_MEM_NOC': 'qnm_mnoc_hf', 'ICBID_SLAVE_MNOC_HF_MEM_NOC': 'qns_mem_noc_hf',
 'ICBID_MASTER_PCIE_0': 'xm_pcie3_0', 'ICBID_MASTER_PCIE_1': 'xm_pcie3_1',
 'ICBID_MASTER_QUP_0': 'qhm_qup0', 'ICBID_MASTER_QUP_1': 'qhm_qup1', 'ICBID_MASTER_QUP_2': 'qhm_qup2',
 'ICBID_MASTER_ROTATOR': 'qxm_rot', 'ICBID_MASTER_SDCC_2': 'xm_sdc2', 'ICBID_MASTER_UFS_MEM': 'xm_ufs_mem',
 'ICBID_MASTER_USB3_0': 'xm_usb3_0', 'ICBID_MASTER_USB3_1': 'xm_usb3_1',
 'ICBID_MASTER_VIDEO_P0': 'qnm_video0', 'ICBID_SLAVE_LLCC': 'qns_llcc',
}
D = open(dsl).read()
routes = sorted(set(re.findall(r'"BUSARB",\s*Package \(0x[0-9A-F]+\)\s*\{\s*\w+,\s*"(\w+)",\s*"(\w+)"', D)))

def path(a, b):
    prev = {a: None}; q = collections.deque([a])
    while q:
        x = q.popleft()
        if x == b:
            break
        for y in nodes[x]['links']:
            if y not in prev:
                prev[y] = x; q.append(y)
    if b not in prev:
        return None
    p = [b]
    while prev[p[-1]] is not None:
        p.append(prev[p[-1]])
    return p[::-1]

masters, slaves = {}, {}   # linux node -> (symbol, id)
def sym(n, kind):
    for k, v in KONA.items():
        if v == n and k.startswith('ICBID_' + kind):
            return k
    return 'ICBID_%s_LX_%s' % (kind, n.upper())
def add(tab, n, kind):
    if n not in tab:
        tab[n] = (sym(n, kind), len(tab) + 1)
    return tab[n][1]
hops, rts, skipped = [], [], []
for ms, ss in routes:
    if ms not in KONA or ss not in KONA:
        skipped.append((ms, ss, 'no node')); continue
    p = path(KONA[ms], KONA[ss])
    if not p or len(p) % 2:
        skipped.append((ms, ss, 'no path' if not p else 'odd path %s' % p)); continue
    # register the DSDT symbols themselves under their own names
    off = len(hops)
    for i in range(0, len(p), 2):
        hops.append((add(masters, p[i], 'MASTER'), add(slaves, p[i + 1], 'SLAVE')))
    rts.append((ms, ss, masters[KONA[ms]][1], slaves[KONA[ss]][1], off, len(hops) - off))
# aliases (two DSDT symbols -> one Linux node): extra node rows with the same id
alias_m = [(k, KONA[k]) for k in KONA if k.startswith('ICBID_MASTER') and KONA[k] in masters and masters[KONA[k]][0] != k]

# ---- bcm_nodes_gen.c
o = ['/* generated by tools/gen_icb_8250.py from Linux interconnect/qcom/sm8250.c. */', '#include "bus.h"', '',
     'const unsigned char icb_bcm_relatives[] = {0};', 'const unsigned int icb_bcm_relative_cnt = 0u;', '',
     'const icb_bcm_node_t icb_bcm_nodes[] = {']
for name, ka, mask, ns in bcms:
    if mask:
        o.append('    {"%s", BCM_KIND_VECTOR, 0x%Xu, 0u, 0u, %du},' % (name, mask, int(ka)))
    else:
        o.append('    {"%s", BCM_KIND_BANDWIDTH, 0x0u, 0u, 0u, %du},' % (name, int(ka)))
o += ['};', 'const unsigned int icb_bcm_node_cnt = %du;' % len(bcms), '']
flat, rows_m, rows_s = [], [], []
def row(symb, nid, n):
    first = len(flat); flat.extend(node_bcms[n])
    return '    {"%s", %du, "%s", %du, %du, %du, %du},' % (symb, nid, n, nodes[n]['bw'], nodes[n]['ch'], first, len(node_bcms[n]))
for n, (s, i) in masters.items():
    rows_m.append(row(s, i, n))
for k, n in alias_m:
    rows_m.append(row(k, masters[n][1], n))
for n, (s, i) in slaves.items():
    rows_s.append(row(s, i, n))
o += ['const unsigned char icb_node_bcms[] = {%s};' % ', '.join(map(str, flat or [0])),
      'const unsigned int icb_node_bcm_cnt = %du;' % len(flat), '',
      'const icb_node_t icb_master_nodes[] = {'] + rows_m + ['};', 'const unsigned int icb_master_node_cnt = %du;' % len(rows_m), '',
      'const icb_node_t icb_slave_nodes[] = {'] + rows_s + ['};', 'const unsigned int icb_slave_node_cnt = %du;' % len(rows_s), '']
open(out_bcm, 'w').write('\n'.join(o))
# ---- catalog include (masters/slaves/hops/routes)
c = ['/* generated by SystemLibs/ICB/8250/tools/gen_icb_8250.py - SM8250 ICB catalog. */', 'const icb_entry_t icb_masters[] = {']
for n, (s, i) in masters.items():
    c.append('    {%du, "%s", "%s", "sm8250", %du},' % (i, s, n, nodes[n]['bw']))
for k, n in alias_m:
    c.append('    {%du, "%s", "%s", "sm8250", %du},' % (masters[n][1], k, n, nodes[n]['bw']))
c += ['};', 'const unsigned int icb_master_cnt = (unsigned int)(sizeof(icb_masters) / sizeof(icb_masters[0]));',
      'const icb_entry_t icb_slaves[] = {']
for n, (s, i) in slaves.items():
    c.append('    {%du, "%s", "%s", "sm8250", %du},' % (i, s, n, nodes[n]['bw']))
c += ['};', 'const unsigned int icb_slave_cnt = (unsigned int)(sizeof(icb_slaves) / sizeof(icb_slaves[0]));']
open(out_cat, 'w').write('\n'.join(c) + '\n')
r = ['/* generated by gen_icb_8250.py */', 'const icb_hop_t icb_hops[] = {'] + ['    {%du, %du},' % h for h in hops] + \
    ['};', 'const unsigned int icb_hop_cnt = (unsigned int)(sizeof(icb_hops) / sizeof(icb_hops[0]));',
     'const icb_route_t icb_routes[] = {'] + ['    {%du, %du, %du, %du}, /* %s -> %s */' % (a, b, off, cnt, ms, ss) for ms, ss, a, b, off, cnt in rts] + \
    ['};', 'const unsigned int icb_route_cnt = (unsigned int)(sizeof(icb_routes) / sizeof(icb_routes[0]));']
open(out_routes, 'w').write('\n'.join(r) + '\n')
print('bcms', len(bcms), 'masters', len(masters), '+%d aliases' % len(alias_m), 'slaves', len(slaves), 'routes', len(rts), 'hops', len(hops))
for s in skipped: print('skipped', s)
